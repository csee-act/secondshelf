import {createRequire} from 'node:module';
import {existsSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const runtime=process.env.PLAYWRIGHT_PATH||join(process.env.USERPROFILE||'','\.cache\codex-runtimes\codex-primary-runtime\dependencies\node\node_modules\playwright');
const {chromium}=require(existsSync(runtime)?runtime:'playwright');
