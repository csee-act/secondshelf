  await page.getByLabel('Where does it live?').fill('Private test room · private shelf');
  await page.locator('#f-description').fill('A useful test cooker, with a removable pot.');
  await page.getByRole('button',{name:'1: Ready to let go',exact:true}).click();
  await page.getByText('A little more about this item',{exact:true}).click();
  await page.locator('#f-lastUsed').fill('2024-01-01');
  await page.locator('#f-lastMoved').fill('2025-01-01');
  await page.locator('#f-story').fill('PRIVATE STORY MUST NEVER BE PUBLISHED');
  await page.locator('#f-estimate').fill('60');
  await page.locator('#f-condition').selectOption('Good');
  await page.getByRole('button',{name:'Save my item',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  await page.getByRole('button',{name,exact:true}).waitFor();
  timings.push({viewport:mobile?'mobile':'desktop',captureMs:Date.now()-started});
  await page.reload();await page.getByRole('button',{name,exact:true}).waitFor();
  await page.getByRole('button',{name,exact:true}).click();
  await page.getByRole('heading',{name:'Ready for a second chapter?',exact:true}).waitFor();
  await page.getByRole('button',{name:'Sell or swap',exact:true}).click();
  assert.equal(await page.locator('.publish-preview').innerText().then(t=>t.includes('PRIVATE STORY')),false);
  if(mobile){await page.getByRole('button',{name:'Swap',exact:true}).click();await page.getByLabel('What would you like in return?').fill('A few books');}
  else await page.locator('#f-price').fill('45');
  if(!mobile)await page.screenshot({path:join(out,'listing-preview.png'),fullPage:true});
  await page.getByRole('button',{name:'Publish to community',exact:true}).click();
  await page.getByRole('heading',{name:'Good things, shared.',exact:true}).waitFor();
  await page.getByRole('button',{name,exact:true}).waitFor();
  if(!mobile){
    await page.screenshot({path:join(out,'community.png'),fullPage:true});
    const visitor=await browser.newContext();const p=await visitor.newPage();await p.goto(base+'/#community');await p.getByRole('button',{name,exact:true}).waitFor();assert.equal(await p.locator('body').innerText().then(t=>t.includes('PRIVATE STORY')),false);await visitor.close();
  }
  await page.getByRole('button',{name,exact:true}).click();
  await page.getByRole('button',{name:'Withdraw listing',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  await page.getByRole('button',{name,exact:true}).waitFor({state:'detached'});
  if(mobile)await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('link',{name:'My inventory',exact:true}).click();
  await page.getByRole('button',{name,exact:true}).click();
  await page.getByRole('button',{name:'Used today',exact:true}).click();
  await page.getByText('Still part of your everyday',{exact:true}).waitFor();
